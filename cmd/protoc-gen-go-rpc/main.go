package main

import (
	"fmt"
	"strconv"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

const (
	contextPackage = protogen.GoImportPath("context")
	protoPackage   = protogen.GoImportPath("google.golang.org/protobuf/proto")
	rpcPackage     = protogen.GoImportPath("github.com/2comjie/nova/rpc")
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL | pluginpb.CodeGeneratorResponse_FEATURE_SUPPORTS_EDITIONS)
		gen.SupportedEditionsMinimum = descriptorpb.Edition_EDITION_PROTO2
		gen.SupportedEditionsMaximum = descriptorpb.Edition_EDITION_2024
		for _, file := range gen.Files {
			if file.Generate && len(file.Services) != 0 {
				if err := generateFile(gen, file); err != nil {
					return err
				}
			}
		}
		return nil
	})
}

func generateFile(gen *protogen.Plugin, file *protogen.File) error {
	for _, service := range file.Services {
		for _, method := range service.Methods {
			if method.Desc.IsStreamingClient() || method.Desc.IsStreamingServer() {
				return fmt.Errorf("rpc: streaming is not supported: %s", method.Desc.FullName())
			}
		}
	}
	g := gen.NewGeneratedFile(file.GeneratedFilenamePrefix+"_rpc.pb.go", file.GoImportPath)
	g.P("// Code generated by protoc-gen-go-rpc. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P("package ", file.GoPackageName)
	for _, service := range file.Services {
		name := service.GoName
		clientName := strings.ToLower(name[:1]) + name[1:] + "Client"
		for _, method := range service.Methods {
			g.P("const ", name, "_", method.GoName, "_FullMethodName = ", strconv.Quote("/"+string(service.Desc.FullName())+"/"+string(method.Desc.Name())))
		}
		g.P(service.Comments.Leading, "type ", name, "Client interface {")
		for _, method := range service.Methods {
			g.P(method.Comments.Leading, method.GoName, "(ctx ", contextPackage.Ident("Context"), ", request *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", error)")
		}
		g.P("}")
		g.P("type ", clientName, " struct { cc ", rpcPackage.Ident("Invoker"), " }")
		g.P("func New", name, "Client(cc ", rpcPackage.Ident("Invoker"), ") ", name, "Client { return &", clientName, "{cc: cc} }")
		for _, method := range service.Methods {
			g.P("func (c *", clientName, ") ", method.GoName, "(ctx ", contextPackage.Ident("Context"), ", request *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", error) {")
			g.P("response := new(", method.Output.GoIdent, ")")
			g.P("if err := c.cc.Invoke(ctx, ", name, "_", method.GoName, "_FullMethodName, request, response); err != nil { return nil, err }")
			g.P("return response, nil")
			g.P("}")
		}
		g.P(service.Comments.Leading, "type ", name, "Server interface {")
		for _, method := range service.Methods {
			g.P(method.Comments.Leading, method.GoName, "(ctx ", contextPackage.Ident("Context"), ", request *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", *", rpcPackage.Ident("Error"), ")")
		}
		g.P("}")
		g.P("type Unimplemented", name, "Server struct {}")
		for _, method := range service.Methods {
			g.P("func (Unimplemented", name, "Server) ", method.GoName, "(ctx ", contextPackage.Ident("Context"), ", request *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", *", rpcPackage.Ident("Error"), ") {")
			g.P("return nil, ", rpcPackage.Ident("NewError"), "(", rpcPackage.Ident("CodeNotFound"), ", ", strconv.Quote("method "+method.GoName+" not implemented"), ")")
			g.P("}")
		}
		g.P("func Register", name, "Server(server *", rpcPackage.Ident("Server"), ", implementation ", name, "Server) {")
		for _, method := range service.Methods {
			g.P("server.Register(", name, "_", method.GoName, "_FullMethodName, func(ctx ", contextPackage.Ident("Context"), ", body []byte) (", protoPackage.Ident("Message"), ", *", rpcPackage.Ident("Error"), ") {")
			g.P("request := new(", method.Input.GoIdent, ")")
			g.P("if err := ", protoPackage.Ident("Unmarshal"), "(body, request); err != nil { return nil, ", rpcPackage.Ident("NewError"), "(", rpcPackage.Ident("CodeInvalidArgument"), ", err.Error()) }")
			g.P("return implementation.", method.GoName, "(ctx, request)")
			g.P("})")
		}
		g.P("}")
	}
	return nil
}
