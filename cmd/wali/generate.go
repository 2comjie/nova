//go:embed templates
var templates embed.FS

type templateOutput struct {
	Template string
	Path     string
}

type generatedGateConfig struct {
	Gate generatedGate `yaml:"gate"`
}

type generatedGate struct {
	Routes []generatedGateRoute `yaml:"routes"`
}

type generatedGateRoute struct {
	ID     string              `yaml:"id"`
	Routes []uint32            `yaml:"routes"`
	Target generatedGateTarget `yaml:"target"`
}

type generatedGateTarget struct {
	Mode    string `yaml:"mode"`
	Service string `yaml:"service"`
	Balance string `yaml:"balance"`
}

func renderNew(root string, output templateOutput, data any) error {
	body, err := templates.ReadFile(output.Template)
	if err != nil {
		return err
	}
	tmpl, err := template.New(filepath.Base(output.Template)).
		Option("missingkey=error").
		Parse(string(body))
	if err != nil {
		return err
	}
	var result bytes.Buffer
	if err := tmpl.Execute(&result, data); err != nil {
		return err
	}

	content := result.Bytes()
	if filepath.Ext(output.Path) == ".go" {
		content, err = format.Source(content)
		if err != nil {
			return fmt.Errorf("wali: 格式化模板失败 path=%s: %w", output.Path, err)
		}
	}
	return writeFile(filepath.Join(root, output.Path), content, false)
}

func renderIfMissing(root string, output templateOutput, data any) error {
	if _, err := os.Stat(filepath.Join(root, output.Path)); err == nil {
		return nil
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return renderNew(root, output, data)
}

func generateRoutes(root string, project Project, manifest RouteManifest) error {
	routes := append([]RouteSpec(nil), manifest.Routes...)
	sort.Slice(routes, func(i, j int) bool {
		return routes[i].ID < routes[j].ID
	})

	var goFile bytes.Buffer
	goFile.WriteString("// Code generated by wali. DO NOT EDIT.\n\n")
	goFile.WriteString("package route\n")
	if len(routes) > 0 {
		goFile.WriteString("\nconst (\n")
		for _, route := range routes {
			_, _ = fmt.Fprintf(
				&goFile,
				"\t%s uint32 = %d\n",
				goIdentifier(route.Name),
				route.ID,
			)
		}
		goFile.WriteString(")\n")
	}
	formatted, err := format.Source(goFile.Bytes())
	if err != nil {
		return err
	}
	if err := writeFile(
		filepath.Join(root, "internal/gen/route/routes_gen.go"),
		formatted,
		true,
	); err != nil {
		return err
	}

	config := generatedGateConfig{}
	for _, route := range routes {
		config.Gate.Routes = append(config.Gate.Routes, generatedGateRoute{
			ID:     route.Name,
			Routes: []uint32{route.ID},
			Target: generatedGateTarget{
				Mode:    "balance",
				Service: route.Node,
				Balance: "weighted_round_robin",
			},
		})
	}
	yamlBody, err := yaml.Marshal(config)
	if err != nil {
		return err
	}
	yamlBody = append([]byte("# Code generated by wali. DO NOT EDIT.\n"), yamlBody...)
	return writeFile(
		filepath.Join(root, "configs/gate/routes_gen.yaml"),
		yamlBody,
		true,
	)
}

func generateRPCClient(root string, project Project) error {
	nodes := append([]NodeSpec(nil), project.Nodes...)
	sort.Slice(nodes, func(i, j int) bool {
		return nodes[i].Name < nodes[j].Name
	})

	var file bytes.Buffer
	file.WriteString("// Code generated by wali. DO NOT EDIT.\n\n")
	file.WriteString("package rpcclient\n\n")
	file.WriteString("import (\n")
	file.WriteString(
		"\twalirpc \"github.com/2comjie/wali/rpc/client\"\n",
	)
	for _, node := range nodes {
		_, _ = fmt.Fprintf(
			&file,
			"\t%spb %q\n",
			node.Name,
			project.Module+"/api/server/"+node.Name,
		)
	}
	file.WriteString(")\n\n")
	file.WriteString("// Client 聚合当前进程使用的全部内部RPC Client。\n")
	file.WriteString("// 所有强类型Client共用Base中的连接池和服务发现订阅。\n")
	file.WriteString("type Client struct {\n")
	file.WriteString("\tBase *walirpc.Client\n")
	for _, node := range nodes {
		_, _ = fmt.Fprintf(
			&file,
			"\t%s %spb.%sClient\n",
			goIdentifier(node.Name),
			node.Name,
			goIdentifier(node.Name),
		)
	}
	file.WriteString("}\n\n")
	file.WriteString("// New 创建进程级内部RPC Client聚合对象。\n")
	file.WriteString("func New(base *walirpc.Client) *Client {\n")
	file.WriteString("\treturn &Client{\n")
	file.WriteString("\t\tBase: base,\n")
	for _, node := range nodes {
		_, _ = fmt.Fprintf(
			&file,
			"\t\t%s: %spb.New%sClient(base),\n",
			goIdentifier(node.Name),
			node.Name,
			goIdentifier(node.Name),
		)
	}
	file.WriteString("\t}\n")
	file.WriteString("}\n")

	formatted, err := format.Source(file.Bytes())
	if err != nil {
		return err
	}
	return writeFile(
		filepath.Join(root, "internal/rpcclient/client_gen.go"),
		formatted,
		true,
	)
}

func generateNodeRoutes(
	root string,
	project Project,
	manifest RouteManifest,
	nodeName string,
) error {
	var routes []RouteSpec
	for _, route := range manifest.Routes {
		if route.Node == nodeName {
			routes = append(routes, route)
		}
	}
	sort.Slice(routes, func(i, j int) bool {
		return routes[i].ID < routes[j].ID
	})

	var file bytes.Buffer
	file.WriteString("// Code generated by wali. DO NOT EDIT.\n\n")
	_, _ = fmt.Fprintf(&file, "package %s\n\n", nodeName)
	_, _ = fmt.Fprintf(
		&file,
		"import nodeapp %q\n",
		"github.com/2comjie/wali/app/node",
	)
	if len(routes) > 0 {
		_, _ = fmt.Fprintf(
			&file,
			"import route %q\n",
			project.Module+"/internal/gen/route",
		)
	}
	file.WriteString("\n// Register 注册当前Node的全部业务路由。\n")
	file.WriteString("func Register(router *nodeapp.Router) error {\n")
	for _, route := range routes {
		_, _ = fmt.Fprintf(
			&file,
			"\tif err := router.Handle(route.%s, %s); err != nil {\n"+
				"\t\treturn err\n\t}\n",
			goIdentifier(route.Name),
			handlerIdentifier(route.Name),
		)
	}
	file.WriteString("\treturn nil\n}\n")

	formatted, err := format.Source(file.Bytes())
	if err != nil {
		return err
	}
	return writeFile(
		filepath.Join(root, "internal", nodeName, "routes_gen.go"),
		formatted,
		true,
	)
}

func writeFile(path string, body []byte, overwrite bool) error {
	if !overwrite {
		if _, err := os.Stat(path); err == nil {
			return fmt.Errorf("wali: 文件已经存在，不会覆盖: %s", path)
		} else if !errors.Is(err, os.ErrNotExist) {
			return err
		}
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	mode := os.FileMode(0o644)
	if filepath.Ext(path) == ".sh" {
		mode = 0o755
	}
	return os.WriteFile(path, body, mode)
}

func goIdentifier(value string) string {
	parts := strings.FieldsFunc(value, func(r rune) bool {
		return r == '.' || r == '-' || r == '_'
	})
	var result strings.Builder
	for _, part := range parts {
		result.WriteString(strings.ToUpper(part[:1]))
		result.WriteString(part[1:])
	}
	return result.String()
}

func handlerIdentifier(routeName string) string {
	return "handle" + goIdentifier(routeName)
}

func fileIdentifier(value string) string {
	return strings.NewReplacer(".", "_", "-", "_").Replace(value)
}
