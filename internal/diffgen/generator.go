		if !isMessage(field) {
			continue
		}
		generated.P("if value.", field.GoName, " != nil {")
		generated.P("state.", lowerFirst(field.GoName), " = ", childStateConstructor(generated, message, field, "value."+field.GoName, "state.mark"+field.GoName+"Dirty"))
