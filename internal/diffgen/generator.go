	for _, field := range message.Fields {
		if isScalar(field) {
			generateScalarField(generated, message, field)
		} else if isMessage(field) {
			generateMessageField(generated, message, field)
		} else if field.Desc.IsMap() {
			generateMapField(generated, message, field)
		} else if field.Desc.IsList() {
			generateListField(generated, message, field)
		}
	}
	generateWriteDiff(generated, message)
	generateApplyDiff(generated, message)
	generated.P("func (s *", stateName, ") ClearDirty() {")
	generated.P(generated.QualifiedGoIdent(diffIdent("ClearDirty")), "(s.dirty[:])")
