func lowerFirst(value string) string {
	if value == "" || value[0] < 'A' || value[0] > 'Z' {
		return value
	}
	return string(value[0]+'a'-'A') + value[1:]
}

func diffIdent(name string) protogen.GoIdent {
	return protogen.GoIdent{GoName: name, GoImportPath: diffPackage}
}

