func generateReadListValue(generated *protogen.GeneratedFile, reader string, field *protogen.Field, variable string) {
	if field.Message == nil {
		generated.P(variable, " := ", readScalar(generated, reader, field))
		return
	}
	generated.P(variable, "Data := ", reader, ".Bytes()")
	generated.P(variable, " := &", field.Message.GoIdent, "{}")
	generated.P("if err := ", generated.QualifiedGoIdent(protogen.GoIdent{GoName: "Unmarshal", GoImportPath: protoPackage}), "(", variable, "Data, ", variable, "); err != nil {")
	generated.P("return err")
	generated.P("}")
}

